"""Imports the generic Merchant pawn (#112) rendered by C:/Users/mauro/wgbg-art/merchant/render_merchant.py:
8 tilt steps of a tintable body and an untinted brass trim (256x256 at 193 px per unit, contact point at the centre,
the buildings' camera), and its GLB for the 3D board. Writes MerchantArt.kt with the resource lists.

Kept apart from import_buildings.py (which clears every bld_* file) so a buildings re-import can't drop it.

Usage: py tools/import_merchant.py
"""
from pathlib import Path
import shutil
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(r"C:/Users/mauro/wgbg-art/merchant")
OUT = ROOT / "app/src/main/res/drawable-nodpi"
KT = ROOT / "app/src/main/java/com/mauro/wgbg/MerchantArt.kt"
GLB = ROOT / "app/src/main/assets/filament/default_merchant.glb"
STEPS = 8

for old in OUT.glob("mer_*.webp"):
    old.unlink()
lists = {}
for layer, mid in (("body", ""), ("trim", "_trim")):
    names = []
    for i in range(STEPS):
        name = f"mer_default{mid}_tilt_{i}"
        Image.open(SRC / f"piece_merchant{mid}_tilt_{i}.png").convert("RGBA").save(OUT / f"{name}.webp", quality=90, method=6)
        names.append(name)
    lists[layer] = names
shutil.copy2(SRC / "merchant.glb", GLB)


def kt_list(names):
    return "listOf(" + ", ".join(f"R.drawable.{n}" for n in names) + ")"


KT.write_text("\n".join([
    "package com.mauro.wgbg",
    "",
    "// Generated by tools/import_merchant.py: do not edit by hand.",
    "",
    "/** The generic Merchant pawn (#112): 8 tilt steps, a tintable body and a brass trim, like the buildings. */",
    "object MerchantArt {",
    f"    val DEFAULT = BuildingArt.Piece({kt_list(lists['body'])},",
    f"        {kt_list(lists['trim'])})",
    "}",
    "",
]), encoding="utf-8", newline="\n")
print(f"Imported {2 * STEPS} merchant sprites and {GLB.name}")
