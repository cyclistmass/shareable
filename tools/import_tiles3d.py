"""Imports the V3 3D tiles (Codex's Blender models rendered by Crest; base slab 0.11 hex units, codex/tiles3d 3136099)
into res/drawable-nodpi and writes app/src/main/java/com/mauro/wgbg/Tile3dArt.kt with the resource lists.

Source: <folder>/<terrain>_V3_tilt_<0..7>.png, 512x512 RGBA, orthographic scale 2.65 (193 px per hex unit) with the
hex centre at the frame centre, the hex base and thickness baked in, 8 tilt steps (tilt = 0.96 * i / 7). Saved at
SIZE px to keep memory down (the setting is a preview and loads only when chosen). Old imported files are removed first.

Usage: py tools/import_tiles3d.py <folder with the V3 pngs>
"""
import sys
from pathlib import Path
from art_import import save_webp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/res/drawable-nodpi"
KT = ROOT / "app/src/main/java/com/mauro/wgbg/Tile3dArt.kt"
SRC = Path(sys.argv[1])
# Engine resource order (Timber, Clay, Fleece, Grain, Stone), then the desert.
TERRAINS = ["timber", "clay", "fleece", "grain", "stone", "desert"]
STEPS = 8
SIZE = 384

for old in OUT.glob("t3d_*.webp"):
    old.unlink()

names = {}
for t in TERRAINS:
    names[t] = []
    for i in range(STEPS):
        name = f"t3d_{t}_tilt_{i}"
        save_webp(SRC / f"{t}_V3_tilt_{i}.png", OUT / f"{name}.webp", (SIZE, SIZE), quality=88)
        names[t].append(name)

lines = [
    "package com.mauro.wgbg",
    "",
    "// Generated by tools/import_tiles3d.py: do not edit by hand.",
    "",
    "/**",
    " * The V3 3D tiles (preview): per terrain 8 tilt steps (tilt = 0.96 * i / 7), frames spanning [FRAME_UNITS] hex",
    " * units with the hex centre at the frame centre, base and thickness baked in.",
    " */",
    "object Tile3dArt {",
    "    /** Hex units across one frame (512 px at 193 px per hex unit, orthographic scale 2.65). */",
    "    const val FRAME_UNITS = 2.65f",
    "    /** Timber, Clay, Fleece, Grain, Stone (engine resource order), then the desert. */",
    "    val TERRAINS = listOf(",
]
for t in TERRAINS:
    lines.append("        listOf(" + ", ".join(f"R.drawable.{n}" for n in names[t]) + "),")
lines += ["    )", "}", ""]
KT.write_text("\n".join(lines), encoding="utf8")
print(f"{sum(len(v) for v in names.values())} tiles, Tile3dArt.kt written")
